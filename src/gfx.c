static SDL_FPoint *scratch_get(int n)
{
  if (n > scratch_capacity) {
    int capacity = scratch_capacity ? scratch_capacity : 256;

    while (capacity < n) {
      capacity *= 2;
    }

    SDL_FPoint *grown = (SDL_FPoint *)realloc(scratch, sizeof(SDL_FPoint) * (size_t)capacity);

    if (!grown) {
      return NULL;
    }

    scratch = grown;
    scratch_capacity = capacity;
  }

  return scratch;
}

void gfx_init(SDL_Renderer *renderer)
{
  ren = renderer;
}

void gfx_quit(void)
{
  free(scratch);
  scratch = NULL;
  scratch_capacity = 0;
}

void gfx_set_color(float r, float g, float b, float a)
{
  color.r = r;
  color.g = g;
  color.b = b;
  color.a = a;
  SDL_SetRenderDrawColorFloat(ren, r, g, b, a);
}

void gfx_set_translate(float x, float y)
{
  translate_x = x;
  translate_y = y;
}

void gfx_reset_translate(void)
{
  translate_x = 0.0f;
  translate_y = 0.0f;
}

void gfx_circle_line(float x, float y, float radius)
{
  SDL_FPoint points[CIRCLE_LINE_SEGMENTS + 1];

  for (int i = 0; i <= CIRCLE_LINE_SEGMENTS; i++) {
    float angle = 2.0f * SDL_PI_F * (float)i / CIRCLE_LINE_SEGMENTS;
    points[i].x = translate_x + x + cosf(angle) * radius;
    points[i].y = translate_y + y + sinf(angle) * radius;
  }

  SDL_RenderLines(ren, points, CIRCLE_LINE_SEGMENTS + 1);
}

void gfx_circle_fill(float x, float y, float radius)
{
  SDL_Vertex vertices[CIRCLE_FILL_SEGMENTS + 1];
  int indices[CIRCLE_FILL_SEGMENTS * 3];

  vertices[0].position.x = translate_x + x;
  vertices[0].position.y = translate_y + y;
  vertices[0].color = color;
  vertices[0].tex_coord.x = 0.0f;
  vertices[0].tex_coord.y = 0.0f;

  for (int i = 0; i < CIRCLE_FILL_SEGMENTS; i++) {
    float angle = 2.0f * SDL_PI_F * (float)i / CIRCLE_FILL_SEGMENTS;
    vertices[i + 1].position.x = translate_x + x + cosf(angle) * radius;
    vertices[i + 1].position.y = translate_y + y + sinf(angle) * radius;
    vertices[i + 1].color = color;
    vertices[i + 1].tex_coord.x = 0.0f;
    vertices[i + 1].tex_coord.y = 0.0f;

    indices[i * 3 + 0] = 0;
    indices[i * 3 + 1] = i + 1;
    indices[i * 3 + 2] = (i + 1) % CIRCLE_FILL_SEGMENTS + 1;
  }

  SDL_RenderGeometry(ren, NULL, vertices, CIRCLE_FILL_SEGMENTS + 1,
                     indices, CIRCLE_FILL_SEGMENTS * 3);
}

static void transform_verts(const float *verts, int n, float x, float y, float angle,
                            SDL_FPoint *out)
{
  float c = cosf(angle);
  float s = sinf(angle);

  for (int i = 0; i < n; i++) {
    float vx = verts[i * 2];
    float vy = verts[i * 2 + 1];
    out[i].x = translate_x + x + vx * c - vy * s;
    out[i].y = translate_y + y + vx * s + vy * c;
  }
}

void gfx_polygon_line(const float *verts, int n, float x, float y, float angle)
{
  SDL_FPoint *points = scratch_get(n + 1);

  if (!points) {
    return;
  }

  transform_verts(verts, n, x, y, angle, points);
  points[n] = points[0];
  SDL_RenderLines(ren, points, n + 1);
}

void gfx_line(const float *verts, int n, float x, float y, float angle)
{
  SDL_FPoint *points = scratch_get(n);

  if (!points) {
    return;
  }

  transform_verts(verts, n, x, y, angle, points);
  SDL_RenderLines(ren, points, n);
}

void gfx_points(const SDL_FPoint *points, int n)
{
  if (n <= 0) {
    return;
  }

  if (translate_x == 0.0f && translate_y == 0.0f) {
    SDL_RenderPoints(ren, points, n);
    return;
  }

  SDL_FPoint *shifted = scratch_get(n);

  if (!shifted) {
    return;
  }

  for (int i = 0; i < n; i++) {
    shifted[i].x = points[i].x + translate_x;
    shifted[i].y = points[i].y + translate_y;
  }

  SDL_RenderPoints(ren, shifted, n);
}

void gfx_rect_line(float x, float y, float w, float h)
{
  SDL_FRect rect = { translate_x + x, translate_y + y, w, h };
  SDL_RenderRect(ren, &rect);
}

float gfx_text_height(void)
{
  return (float)(FONT_GLYPH_H * FONT_SCALE);
}

float gfx_text_width(const char *text)
{
  size_t len = strlen(text);

  if (len == 0) {
    return 0.0f;
  }

  return (float)(len * FONT_ADVANCE - FONT_SCALE);
}

void gfx_text(const char *text, float x, float y)
{
  SDL_FRect rects[FONT_GLYPH_W * FONT_GLYPH_H];
  float pen_x = x;

  for (const char *p = text; *p; p++) {
    unsigned char c = (unsigned char)*p;
    const unsigned char *rows = (c >= 32 && c <= 126) ? font_glyphs[c - 32] : font_glyphs['?' - 32];
    int count = 0;

    for (int row = 0; row < FONT_GLYPH_H; row++) {
      for (int col = 0; col < FONT_GLYPH_W; col++) {
        if (rows[row] & (0x10 >> col)) {
          rects[count].x = pen_x + (float)(col * FONT_SCALE);
          rects[count].y = y + (float)(row * FONT_SCALE);
          rects[count].w = (float)FONT_SCALE;
          rects[count].h = (float)FONT_SCALE;
          count++;
        }
      }
    }

    if (count > 0) {
      SDL_RenderFillRects(ren, rects, count);
    }

    pen_x += (float)FONT_ADVANCE;
  }
}

void gfx_text_centered(const char *text, float y, float width)
{
  float x = (width - gfx_text_width(text)) / 2.0f;
  gfx_text(text, floorf(x), y);
}
